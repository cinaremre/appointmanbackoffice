        /// <summary>
        /// Locality kayitlarini veritabanina ekler. Tablo dolu ise hicbir sey yapmaz.
        /// </summary>
        /// <param name="context">Kullanilacak veritabani baglami.</param>
        /// <param name="logger">Seed ilerlemesini raporlamak icin loglayici.</param>
        public static async Task SeedAsync(AppDbContext context, ILogger logger)
        {
            if (await context.Localities.AnyAsync())
            {
                logger.LogInformation("Localities zaten mevcut, atlaniyor.");
                return;
            }

            var localities = new List<Locality>(RawLocalities.Length);

            foreach (var line in RawLocalities)
            {
                // Ham satir formati: <ilceId>:<localityId>:<ad>
                var parts = line.Split(new[] { ':' }, 3);

                var districtId = int.Parse(parts[0], CultureInfo.InvariantCulture);
                var localityId = int.Parse(parts[1], CultureInfo.InvariantCulture);

                localities.Add(new Locality(localityId, districtId, parts[2]));
            }

            if (localities.Count != ExpectedLocalityCount)
            {
                // Beklenmeyen sayi, ID kaymasi anlamina gelir; seed baslatilmaz.
                logger.LogWarning(
                    "Localities seed iptal edildi: beklenen {Expected}, bulunan {Actual}",
                    ExpectedLocalityCount, localities.Count);
                return;
            }

            await context.Localities.AddRangeAsync(localities);
            await context.SaveChangesAsync();

            logger.LogInformation("Localities seed edildi: {Count} locality", localities.Count);
        }
    }
